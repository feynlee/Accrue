extension Body3D {
    /// Where the skin points of `bone` are on the posed body.
    func floorSkin(_ bone: String, _ g: [String: M], _ h: [String: V]) -> [V] {
        guard let at = h[bone], let rest = head[bone], let points = FloorSkin.rest[bone] else { return [] }
        let turn = g[bone] ?? .identity
        return points.map { at + turn * ($0 - rest) }
    }

    /// The lowest point of the skin of `bones`, and the bone it is on.
    func floorLowest(_ bones: [String], _ g: [String: M], _ h: [String: V]) -> (at: V, bone: String)? {
        var best: (at: V, bone: String)?
        for bone in bones {
            for p in floorSkin(bone, g, h) where best == nil || p.z < best!.at.z { best = (p, bone) }
        }
        return best
    }

    /// How high the lowest skin of `bones` is.
    func floorLow(_ bones: [String], _ g: [String: M], _ h: [String: V]) -> Double {
        floorLowest(bones, g, h)?.at.z ?? 0
    }

    /// `root` and every bone that hangs from it.
    func floorBranch(_ root: String) -> [String] {
        var seen: Set<String> = [root]
        var out = [root]
        for bone in rig.bones {
            if let parent = bone.parent, seen.contains(parent) {
                seen.insert(bone.name)
                out.append(bone.name)
            }
        }
        return out
    }

    /// Turns `bones` by `turn` about the world's axes, on top of the turn they have.
    func floorTurn(_ bones: [String], by turn: M, _ g: inout [String: M]) {
        for bone in bones { if let own = g[bone] { g[bone] = turn * own } }
    }
}
